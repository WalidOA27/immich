"""Build the TS weights module and synthetic test fixtures for the LAION B/32 NSFW head.

Usage: python3 -I misc/nsfw/make_fixture.py <weights.npz> <out_dir>
Writes:
  out_dir/laion-clip-b32.weights.ts  base64 float32 blobs + shapes
  out_dir/nsfw.fixture.json          synthetic unit-norm embeddings and reference scores
No real user embeddings are used: vectors are seeded random, and two are pushed by
gradient ascent/descent on the score so the fixture covers low, mid and high outputs.
"""
import base64
import json
import sys

import numpy as np

KEY = "layer_with_weights-{}|{}|.ATTRIBUTES|VARIABLE_VALUE"


def load(path):
    w = np.load(path)
    g = lambda i, p: w[KEY.format(i, p)].astype(np.float32)
    return {
        "mean": g(1, "mean"), "variance": g(1, "variance"),
        "dense1Kernel": g(2, "kernel"), "dense1Bias": g(2, "bias"),
        "dense2Kernel": g(3, "kernel"), "dense2Bias": g(3, "bias"),
        "dense3Kernel": g(4, "kernel"), "dense3Bias": g(4, "bias"),
    }


def forward(h, x):
    n = (x - h["mean"]) / np.sqrt(np.maximum(h["variance"], 1e-7))
    a1 = n @ h["dense1Kernel"] + h["dense1Bias"]
    r1 = np.maximum(a1, 0)
    a2 = r1 @ h["dense2Kernel"] + h["dense2Bias"]
    r2 = np.maximum(a2, 0)
    z = r2 @ h["dense3Kernel"] + h["dense3Bias"]
    return 1 / (1 + np.exp(-z[0])), (n, a1, a2)


def grad(h, x):
    s, (n, a1, a2) = forward(h, x)
    dz = np.array([1.0])
    d2 = (h["dense3Kernel"] @ dz) * (a2 > 0)
    d1 = (h["dense2Kernel"] @ d2) * (a1 > 0)
    dn = h["dense1Kernel"] @ d1
    return dn / np.sqrt(np.maximum(h["variance"], 1e-7))


def push(h, x, sign, target, steps=500, lr=0.02):
    for _ in range(steps):
        s, _ = forward(h, x)
        if (sign > 0 and s >= target) or (sign < 0 and s <= target):
            break
        x = x + sign * lr * grad(h, x)
        x = x / np.linalg.norm(x)
    return x


def main(weights, out_dir):
    h = load(weights)
    rng = np.random.default_rng(42)
    base = h["mean"].astype(np.float64)
    std = np.sqrt(h["variance"].astype(np.float64))
    start = base + 0.5 * std * rng.standard_normal(512)
    high = push(h, start / np.linalg.norm(start), +1, 0.999, steps=4000, lr=0.002)
    low = rng.standard_normal(512)
    low = low / np.linalg.norm(low)
    mix = lambda t: (lambda v: v / np.linalg.norm(v))((1 - t) * low + t * high)
    vecs = []
    for target in (0.02, 0.2, 0.5, 0.8, 0.98):
        lo, hi = 0.0, 1.0
        for _ in range(60):
            mid = (lo + hi) / 2
            if forward(h, mix(mid))[0] < target:
                lo = mid
            else:
                hi = mid
        vecs.append(mix(hi))
    cases = []
    for v in vecs:
        v32 = v.astype(np.float32)
        s, _ = forward(h, v32.astype(np.float64))
        cases.append({"embedding": [float(f) for f in v32], "score": float(s)})
    json.dump({"model": "laion-clip-b32", "cases": cases}, open(f"{out_dir}/nsfw.fixture.json", "w"))
    lines = [
        "// Generated by misc/nsfw/make_fixture.py from LAION-AI/CLIP-based-NSFW-Detector",
        "// (clip_autokeras_nsfw_b32, MIT). Do not edit by hand.",
        "export const LAION_CLIP_B32 = {",
    ]
    for k, v in h.items():
        b64 = base64.b64encode(np.ascontiguousarray(v, dtype="<f4").tobytes()).decode()
        lines.append(f"  {k}: {{ shape: {list(v.shape)}, data: '{b64}' }},")
    lines.append("} as const;")
    open(f"{out_dir}/laion-clip-b32.weights.ts", "w").write("\n".join(lines) + "\n")
    print("scores:", [round(c["score"], 6) for c in cases])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
